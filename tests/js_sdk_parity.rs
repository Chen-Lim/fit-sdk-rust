fn memo_glob_integration_vectors_match_js_sdk() {
    let cases: &[(&str, &[u8], u16, &str, &str)] = &[
        ("simple", FIT_FILE_MEMO_GLOB_SIMPLE, 27, "notes", "string"),
        (
            "lorem_ipsum",
            FIT_FILE_MEMO_GLOB_LOREM_IPSUM,
            27,
            "notes",
            LOREM_IPSUM,
        ),
        (
            "multibyte",
            FIT_FILE_MEMO_GLOB_MULTIBYTE,
            27,
            "notes",
            JAPANESE_MULTIBYTE,
        ),
        (
            "unknown_target_field",
            FIT_FILE_MEMO_GLOB_UNKNOWN_TARGET_FIELD,
            27,
            "250",
            "string",
        ),
        (
            "unknown_target_mesg",
            FIT_FILE_MEMO_GLOB_UNKNOWN_TARGET_MESG,
            1000,
            "250",
            "string",
        ),
    ];

    for &(label, bytes, target_mesg_num, target_field_name, expected) in cases {
        let (msgs, errs) = Decoder::builder(bytes)
            .decode_memo_glob(true)
            .build()
            .read_all();
        assert!(errs.is_empty(), "{label}: decode errors: {errs:?}");
        let target = msgs
            .iter()
            .find(|m| m.global_mesg_num == target_mesg_num)
            .unwrap_or_else(|| panic!("{label}: missing target mesg {target_mesg_num}"));
        let field = target
            .field(target_field_name)
            .unwrap_or_else(|| panic!("{label}: missing target field `{target_field_name}`"));
        assert_eq!(
            field.value,
            Value::String(expected.to_string()),
            "{label}: reassembled string mismatch"
        );
    }
}
