//! Garmin JS SDK parity integration tests.
//!
//! Exercises byte vectors and real `.fit` fixtures copied from the official
//! `@garmin/fitsdk` JavaScript test suite (`test/decoder.test.js` and
//! `test/utils-memo-glob.test.js`).

use std::path::PathBuf;

use fit::{check_integrity, is_fit, Decoder, FieldKind, FitError, Message, Value};

fn fixture_path(name: &str) -> PathBuf {
    let mut p = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    p.push("tests/fixtures/test_data");
    p.push(name);
    p
}

fn read_fixture(name: &str) -> Vec<u8> {
    std::fs::read(fixture_path(name)).expect("fixture must be readable")
}

fn read_fixture_string(name: &str) -> String {
    std::fs::read_to_string(fixture_path(name)).expect("text fixture must be readable")
}

fn field_f64(msg: &Message, name: &str) -> f64 {
    msg.field(name)
        .unwrap_or_else(|| panic!("missing field `{name}` on `{}`", msg.name))
        .value
        .as_f64()
        .unwrap_or_else(|| panic!("expected numeric value for `{name}`"))
}

#[cfg(feature = "chrono")]
fn timestamp_fit_secs(msg: &Message, name: &str) -> u32 {
    let dt = msg
        .field(name)
        .unwrap_or_else(|| panic!("missing datetime field `{name}`"))
        .value
        .as_datetime()
        .expect("expected Value::DateTime");
    u32::try_from(dt.timestamp() - fit::datetime::FIT_EPOCH_OFFSET_SECS)
        .expect("FIT epoch seconds must be non-negative u32")
}

#[cfg(not(feature = "chrono"))]
fn timestamp_fit_secs(msg: &Message, name: &str) -> u32 {
    match &msg
        .field(name)
        .unwrap_or_else(|| panic!("missing datetime field `{name}`"))
        .value
    {
        Value::DateTime(secs) => *secs,
        Value::UInt(secs) => u32::try_from(*secs).expect("fits in u32"),
        other => panic!("expected Value::DateTime(u32) or UInt, got {other:?}"),
    }
}

